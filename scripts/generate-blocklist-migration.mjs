import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import console from 'node:console';
import { URL, fileURLToPath } from 'node:url';

const directory = new URL('../data/comment-blocklist/', import.meta.url);
const languages = readdirSync(directory)
  .filter((name) => /^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(name))
  .sort();
const terms = new Map();
for (const language of languages) {
  for (const line of readFileSync(new URL(language, directory), 'utf8').split(
    /\r?\n/,
  )) {
    const term = line.normalize('NFC').trim();
    if (!term) continue;
    if ([...term].length > 120 || term.includes('\0'))
      throw new Error(`Invalid term in ${language}`);
    const key = term.toLowerCase();
    if (!terms.has(key)) terms.set(key, term);
  }
}
const sql = `-- Generated by scripts/generate-blocklist-migration.mjs. Do not edit by hand.
-- Source, pinned snapshot and CC BY 4.0 attribution: docs/comment-blocklist.md
-- ${languages.length} language/region files; ${terms.size} normalized, case-insensitive unique terms.
-- Keep existing editorial entries. Never re-seed deleted words at application startup.
INSERT INTO public.comment_blocklist (term)
VALUES
${[...terms.values()].map((term) => `  ('${term.replaceAll("'", "''")}')`).join(',\n')}
ON CONFLICT DO NOTHING;
`;
const migration = new URL(
  '../supabase/migrations/20261015091958_import_multilingual_comment_blocklist.sql',
  import.meta.url,
);
if (process.argv.includes('--check')) {
  if (readFileSync(migration, 'utf8') !== sql)
    throw new Error('Blocklist migration is out of date');
} else writeFileSync(migration, sql);
console.log(
  `${languages.length} files → ${terms.size} terms: ${fileURLToPath(migration)}`,
);

// Editorial additions are independent from the immutable upstream import.
const editorialImports = [
  ['de-ergaenzungen.txt', '20261015151844_extend_german_comment_blocklist.sql'],
  ['de-rassismus.txt', '20261015152310_add_german_racist_terms.sql'],
];
for (const [source, filename] of editorialImports) {
  const extraSource = new URL(source, directory);
  const extraTerms = new Map();
  for (const line of readFileSync(extraSource, 'utf8').split(/\r?\n/)) {
    const term = line.normalize('NFC').trim();
    if (!term) continue;
    if ([...term].length > 120 || term.includes('\0'))
      throw new Error(`Invalid German editorial term in ${source}`);
    extraTerms.set(term.toLowerCase(), term);
  }
  const extraSql = `-- Generated by scripts/generate-blocklist-migration.mjs.
-- German editorial additions for moderation, not endorsements.
-- Source: data/comment-blocklist/${source} (${extraTerms.size} entries).
-- Preserve existing entries and previously applied import history.
INSERT INTO public.comment_blocklist (term)
VALUES
${[...extraTerms.values()].map((term) => `  ('${term.replaceAll("'", "''")}')`).join(',\n')}
ON CONFLICT DO NOTHING;
`;
  const extraMigration = new URL(
    `../supabase/migrations/${filename}`,
    import.meta.url,
  );
  if (process.argv.includes('--check')) {
    if (readFileSync(extraMigration, 'utf8') !== extraSql)
      throw new Error(`German blocklist additions are out of date: ${source}`);
  } else writeFileSync(extraMigration, extraSql);
  console.log(
    `${extraTerms.size} German editorial entries: ${fileURLToPath(extraMigration)}`,
  );
}
