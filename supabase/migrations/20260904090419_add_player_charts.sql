create table public.player_charts (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  chart_type text not null default 'radar' check (chart_type in ('radar')),
  title text not null check (char_length(title) between 3 and 120),
  description text,
  metrics jsonb not null check (
    jsonb_typeof(metrics) = 'array'
    and jsonb_array_length(metrics) between 3 and 10
  ),
  sort_order smallint not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index player_charts_player_sort_idx
  on public.player_charts (player_id, sort_order, id);

alter table public.player_charts enable row level security;

revoke all on table public.player_charts from anon, authenticated;
grant select on table public.player_charts to anon, authenticated;
grant insert, update, delete on table public.player_charts to authenticated;
grant usage, select on sequence public.player_charts_id_seq to authenticated;

create policy "Player charts are publicly readable"
  on public.player_charts for select to anon, authenticated
  using (true);

create policy "Admin editors can insert player charts"
  on public.player_charts for insert to authenticated
  with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admin editors can update player charts"
  on public.player_charts for update to authenticated
  using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin')
  with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admin editors can delete player charts"
  on public.player_charts for delete to authenticated
  using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');
